/** Writes the generated contract to contracts/parts-management.openapi.yaml. */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

import { stringify } from 'yaml';

import { buildOpenApi } from '../src/openapi';

export const CONTRACT_PATH = path.resolve(__dirname, '..', '..', '..', 'contracts', 'parts-management.openapi.yaml');

export const render = () => `# Generated by components/parts-management (npm run openapi). Do not edit by hand.\n${stringify(buildOpenApi(), { lineWidth: 0 })}`;

if (require.main === module) {
  writeFileSync(CONTRACT_PATH, render());
  console.log(`wrote ${path.relative(process.cwd(), CONTRACT_PATH)}`);
}
